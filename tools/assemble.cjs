const fs = require("fs");
const path = require("path");
const { pack } = require("msgpackr");

const root = path.resolve(__dirname, "..");
const configuration = process.argv[2] || "Release";
if (!["Release", "Debug"].includes(configuration))
  throw new Error("Invalid configuration");
const output = path.join(root, "dist", "Peacock");
const original = path.join(root, "vendor", "original");
const patcher = path.join(
  root,
  "src",
  "Peacock",
  "bin",
  configuration,
  "net46",
  "Peacock.exe",
);
if (!fs.existsSync(patcher))
  throw new Error("Compile the patcher with build.ps1 first.");
fs.mkdirSync(output, { recursive: true });

// Copy runtime dependencies, then assemble all maintained code and data.
for (const directory of ["images"]) {
  fs.cpSync(path.join(original, directory), path.join(output, directory), {
    recursive: true,
  });
}
fs.mkdirSync(path.join(output, "resources"), { recursive: true });
for (const file of fs.readdirSync(path.join(original, "resources"))) {
  if (file.endsWith(".rpkg"))
    fs.copyFileSync(
      path.join(original, "resources", file),
      path.join(output, "resources", file),
    );
}
let packages = 0;
function encodeData(directory) {
  for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
    const input = path.join(directory, entry.name);
    if (entry.isDirectory()) encodeData(input);
    else if (entry.name.endsWith(".json")) {
      const relative = path
        .relative(path.join(root, "data"), input)
        .replace(/\.json$/, ".prp");
      const target = path.join(output, "resources", relative);
      fs.mkdirSync(path.dirname(target), { recursive: true });
      fs.writeFileSync(
        target,
        pack(JSON.parse(fs.readFileSync(input, "utf8"))),
      );
      packages++;
    }
  }
}
encodeData(path.join(root, "data"));
fs.cpSync(
  path.join(root, "src/Peacock/WebUI"),
  path.join(output, "webui/dist"),
  {
    recursive: true,
  },
);
fs.copyFileSync(patcher, path.join(output, "Peacock.exe"));
// Remove only the obsolete launcher generated by earlier versions of this build.
const legacyPatcher = path.join(output, "PeacockPatcher.exe");
if (fs.existsSync(legacyPatcher)) fs.unlinkSync(legacyPatcher);
// Retire only the loose runtime files generated by the previous packaging format.
for (const relative of [
  "chunk0.js",
  "server-host.cjs",
  "nodedist/node.exe",
  "nodedist/LICENSE",
]) {
  const legacy = path.resolve(output, relative);
  if (!legacy.startsWith(output + path.sep))
    throw new Error("Invalid legacy output path");
  if (fs.existsSync(legacy)) fs.unlinkSync(legacy);
}
const legacyRuntime = path.join(output, "nodedist");
if (fs.existsSync(legacyRuntime) && fs.readdirSync(legacyRuntime).length === 0)
  fs.rmdirSync(legacyRuntime);
fs.mkdirSync(path.join(output, "licenses"), { recursive: true });
fs.copyFileSync(
  path.join(original, "nodedist/LICENSE"),
  path.join(output, "licenses/Node.js.txt"),
);
const serverSource = fs.readFileSync(
  path.join(root, "src/Peacock/Server/index.js"),
  "utf8",
);
const noticeStart = serverSource.indexOf("/*! Bundled license information:");
if (noticeStart >= 0)
  fs.writeFileSync(
    path.join(output, "licenses/Server-bundle-notices.txt"),
    serverSource.slice(noticeStart),
  );
fs.copyFileSync(path.join(root, ".nvmrc"), path.join(output, ".nvmrc"));
fs.copyFileSync(path.join(root, "README.md"), path.join(output, "README.md"));
const settings = path.join(output, "options.ini");
if (!fs.existsSync(settings))
  fs.copyFileSync(path.join(root, "config/options.ini"), settings);
fs.writeFileSync(
  path.join(output, "Start Peacock.cmd"),
  '@echo off\r\npushd "%~dp0"\r\nstart "" "%~dp0Peacock.exe"\r\npopd\r\n',
);
fs.writeFileSync(
  path.join(output, "Start Server.cmd"),
  '@echo off\r\npushd "%~dp0"\r\nPeacock.exe --server-only\r\npopd\r\npause\r\n',
);
fs.writeFileSync(
  path.join(output, "Tools.cmd"),
  '@echo off\r\npushd "%~dp0"\r\nPeacock.exe --tools\r\npopd\r\npause\r\n',
);
console.log(
  `Built ${output}: combined C# application, server, web interface, and ${packages} data packages.`,
);
console.log(
  "Existing options.ini, userdata, and session files were preserved.",
);
